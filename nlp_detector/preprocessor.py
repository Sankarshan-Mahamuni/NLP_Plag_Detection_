def clean_text(text: str, remove_stopwords: bool = True) -> str:
    """Normalize text by lowercasing, stripping punctuation, and removing stopwords."""
    text = text.lower()
    # Replace punctuation with spaces
    text = re.sub(r'[%s]' % re.escape(string.punctuation), ' ', text)
    # Normalize whitespaces
    tokens = text.split()
    if remove_stopwords:
        tokens = [t for t in tokens if t not in DEFAULT_STOPWORDS and len(t) > 1]
    return " ".join(tokens)


def tokenize(text: str) -> List[str]:
    """Tokenize cleaned text into word tokens."""
    return clean_text(text).split()


def extract_ngrams(tokens: List[str], n: int = 3) -> Set[str]:
    """Generate n-grams from a token sequence for phrase-level overlap analysis."""
    if len(tokens) < n:
        return {" ".join(tokens)} if tokens else set()
    return {" ".join(tokens[i:i + n]) for i in range(len(tokens) - n + 1)}
